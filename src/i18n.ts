const DICTIONARIES: Record<Lang, Dictionary> = { ru, en, de, fr, es, pt, ja, ko, th }

export type Params = Record<string, string | number>
export type T = (key: Key, params?: Params) => string

export function translator(lang: Lang): T {
  const dictionary = DICTIONARIES[lang]
  return (key, params) => {
    const text = dictionary[key]
    return params ? text.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match)) : text
  }
}

/** Ключ из приставки и идентификатора — для надписей, выбираемых по данным (раздел, тир, класс). */
export const keyOf = (prefix: string, id: string | number) => `${prefix}.${id}` as Key

/** Перевод по составному ключу; если такого ключа нет (новый класс из справочника), возвращается запасной текст. */
export function translateOr(t: T, prefix: string, id: string, fallback: string): string {
  return keyOf(prefix, id) in ru ? t(keyOf(prefix, id)) : fallback
}

/** Язык для первого запуска — по языку браузера. */
export function detectLanguage(): Lang {
  const preferred = (typeof navigator === 'undefined' ? '' : navigator.language).toLowerCase().slice(0, 2)
  return LANGUAGES.find((lang) => lang === preferred) ?? 'en'
}
